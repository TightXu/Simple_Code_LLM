def verify_clean_data(jsonl_path, poison_patterns=None, sample_size=100):
    """
    Check the extracted JSONL for residual contamination.
    Sample-print normal vs suspicious code.
    """
    if poison_patterns is None:
        # most dangerous poison patterns (rare to hit, huge harm)
        poison_patterns = [
            ("DjangoMigration", "class Migration(migrations.Migration)"),
            ("DjangoRunPython", "migrations.RunPython"),
            ("DjangoModel", "models.CharField("),
            ("PlotlyValidator", "_plotly_utils.basevalidators"),
            ("PlotlyPlotlyName", "plotly_name="),
            ("Python2Coding", "# -*- coding:"),
            ("Python2Future", "from __future__ import"),
            ("Unittest", "unittest.TestCase"),
            ("Pytest", "pytest.mark."),
            ("Setuptools", "from setuptools import"),
        ]

    print(f"\n{'='*60}")
    print(f"[INFO] verifying data quality: {jsonl_path}")
    print(f"{'='*60}")

    all_codes = []
    with open(jsonl_path, "r", encoding="utf-8") as f:
        for line in f:
            item = json.loads(line)
            text = item.get("text", "")
            if text:
                all_codes.append(text)

    print(f"  total rows: {len(all_codes):,}")

    # check each poison pattern
    total_hits = 0
    for label, pattern in poison_patterns:
        hits = sum(1 for code in all_codes if pattern in code)
        if hits > 0:
            print(f"  [WARN]  {label}: {hits} rows ({hits/len(all_codes)*100:.3f}%)")
            total_hits += hits

    if total_hits == 0:
        print(f"  [OK] zero contamination - none of {len(poison_patterns)} patterns hit")
    else:
        print(f"  [FAIL] {total_hits} contaminated rows remain ({total_hits/len(all_codes)*100:.2f}%)")

    # random sample of normal code
    print(f"\n{'─'*50}")
    print(f"[WRITE] random sample of normal code (5 of the first {sample_size} rows):")
    print(f"{'─'*50}")
    random.seed(42)
    samples = random.sample(all_codes, min(sample_size, len(all_codes)))
    for i, code in enumerate(samples[:5]):
        first_line = code.split('\n')[0].strip()[:80]
        n_lines = len(code.split('\n'))
        n_chars = len(code)
        print(f"\n  [{i+1}] {n_chars} chars, {n_lines} lines")
        print(f"  {first_line}...")
        # show the snippet
        for line in code.split('\n')[1:6]:
            print(f"    {line[:100]}")

    return total_hits


