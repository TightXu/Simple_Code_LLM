def strip_comment_header(code: str) -> str:
    """
    Strip a header comment block containing copyright/license keywords.
    Keep normal comments and docstrings that don't mention copyright.

    Strategy: collect contiguous soft content at the top (shebang, # comments,
    blank lines, docstring, ...), then check the whole block for copyright
    keywords. Strip it all if found, keep it all if not.

    Return the peeled code. If what remains is shorter than 50 chars,
    return the original code instead.
    """
    lines = code.split('\n')
    if not lines:
        return code

    LIC_KEYWORDS = [
        "copyright", "all rights reserved", "licensed under",
        "gnu general public license", "apache license", "mit license",
        "bsd license", "free software foundation", "spdx-license-identifier",
        "this program is free software", "redistribution and use",
        "permission is hereby granted", "this source code",
        "license version", "the free software foundation",
        "distributed under the terms",
    ]

    code_start = 0
    max_rounds = 10

    for _round in range(max_rounds):
        i = code_start
        block_parts = []     # collected text fragments
        has_shebang = False

        while i < len(lines):
            stripped = lines[i].strip()
            s_lower = stripped.lower()

            if s_lower == '':
                # blank line - counts as soft content
                block_parts.append('')
                i += 1
                continue

            if s_lower.startswith('#!'):
                # shebang - always stripped (boilerplate)
                block_parts.append(stripped[2:])
                has_shebang = True
                i += 1
                continue

            if stripped.startswith('#'):
                # # comments - collect content
                block_parts.append(stripped[1:].strip())
                i += 1
                continue

            # check if this is a docstring
            if stripped.startswith('"""') or stripped.startswith("'''"):
                quote = stripped[:3]
                if stripped.count(quote) >= 2 and len(stripped) > 3:
                    # single-line docstring
                    doc_content = stripped[3:-3]
                    block_parts.append(doc_content)
                    i += 1
                else:
                    # multi-line docstring
                    doc_lines = [stripped[3:]] if len(stripped) > 3 else []
                    i += 1
                    doc_found_end = False
                    while i < len(lines):
                        ls = lines[i].strip()
                        if quote in ls:
                            doc_lines.append(ls.replace(quote, ''))
                            i += 1
                            doc_found_end = True
                            break
                        doc_lines.append(lines[i])
                        i += 1
                    if not doc_found_end:
                        break  # unterminated docstring, stop collecting
                    doc_content = '\n'.join(doc_lines)
                    block_parts.append(doc_content)
                continue

            # hit a real code line - stop collecting
            break

        if i == code_start:
            # no soft content collected
            break

        # check whole block for copyright keywords
        block_text = ' '.join(block_parts).lower()
        has_license = any(kw in block_text for kw in LIC_KEYWORDS)

        if has_license or has_shebang:
            code_start = i  # strip the whole block
        else:
            break  # no copyright, keep it, stop the loop

    if code_start >= len(lines):
        return code

    stripped_code = '\n'.join(lines[code_start:]).strip()

    # return if there is content (short code is left to L5 quality filter)
    if stripped_code:
        return stripped_code
    return code



def strip_all_copyright_comments(code: str) -> str:
    """Scan every # comment block in the file; if a block mentions copyright/license
    keywords, strip the whole block. Never reject the file - only comments go,
    the code stays. Also handles repeated header stripping."""
    LIC_KEYWORDS = [
        "copyright", "all rights reserved", "licensed under",
        "gnu general public license", "apache license", "mit license",
        "bsd license", "free software foundation", "spdx-license-identifier",
        "this program is free software", "redistribution and use",
        "permission is hereby granted", "this source code",
        "license version", "the free software foundation",
        "distributed under the terms",
    ]

    # Step 1: multi-round header stripping (top # comments + docstring)
    code = strip_comment_header(code)

    # Step 2: scan all # comment blocks, strip any with copyright keywords
    lines = code.split('\n')
    to_remove = set()
    i = 0
    while i < len(lines):
        stripped = lines[i].strip()
        if stripped.startswith('#'):
            # collect contiguous # comment block
            block_start = i
            block_lines = []
            while i < len(lines):
                s = lines[i].strip()
                if s.startswith('#'):
                    block_lines.append(s[1:].strip())  # drop the #
                    i += 1
                elif s == '':
                    block_lines.append('')
                    i += 1
                else:
                    break
            block_end = i
            block_text = ' '.join(block_lines).lower()

            # check the whole block for copyright keywords
            if any(kw in block_text for kw in LIC_KEYWORDS):
                for j in range(block_start, block_end):
                    to_remove.add(j)
            continue
        i += 1

    if not to_remove:
        return code

    # delete marked lines, also collapse the resulting blank runs
    kept = []
    prev_empty = False
    for idx, line in enumerate(lines):
        if idx in to_remove:
            continue
        is_empty = line.strip() == ''
        if is_empty and prev_empty:
            continue  # collapse consecutive blank lines
        kept.append(line)
        prev_empty = is_empty

    result = '\n'.join(kept).strip()

    # return if content remains (short code goes to the quality filter)
    if result:
        return result
    return code


