def check_l6_autogen(code: str) -> tuple:
    """L6: autogenerated code"""
    for pat in AUTOGEN_PATTERNS:
        # cap matches for some patterns (avoid false positives on normal code)
        matches = re.findall(pat, code)
        if len(matches) >= 3:
            return True, f"L6_autogen:{pat}({len(matches)} hits)"
    return False, ""


def compute_quality_metrics(code: str) -> tuple:
    """
    L5: quality metrics
    Returns (pass: bool, reason: str)
    """
    lines = code.split('\n')
    total = len(lines)
    if total < 2:
        return False, "too_few_lines"

    # non-empty, non-comment-only lines
    non_comment = [l for l in lines if l.strip() and not l.strip().startswith('#')]
    effective = len(non_comment)
    if effective < 2:
        return False, f"effective_lines={effective}"

    # import line ratio
    import_count = sum(1 for l in non_comment
                       if l.strip().startswith(('import ', 'from ')))
    import_ratio = import_count / effective if effective > 0 else 1
    if import_ratio > 0.6:
        return False, f"import_ratio={import_ratio:.0%}"

    # class/decorator ratio
    class_count = sum(1 for l in non_comment
                      if l.strip().startswith(('class ', '@staticmethod', '@classmethod', '@property')))
    decorator_count = sum(1 for l in non_comment
                          if l.strip().startswith('@') and not l.strip().startswith(('@staticmethod', '@classmethod', '@property')))
    class_ratio = (class_count + decorator_count) / effective if effective > 0 else 0
    if class_ratio > 0.7:
        return False, f"class_ratio={class_ratio:.0%}"

    # comment ratio
    comment_lines = sum(1 for l in lines if l.strip().startswith('#'))
    comment_ratio = comment_lines / total if total > 0 else 0
    if comment_ratio > 0.8:
        return False, f"comment_ratio={comment_ratio:.0%}"

    # function defs (must have at least one, with logic lines after)
    has_def = False
    def_idx = -1
    for i, l in enumerate(non_comment):
        if l.strip().startswith('def '):
            has_def = True
            def_idx = i
            # check def is followed by logic lines (not pure pass/return placeholders)
            has_body = False
            for j in range(i + 1, min(i + 5, len(non_comment))):
                body = non_comment[j].strip()
                if body and body != 'pass' and not body.startswith('"""'):
                    has_body = True
                    break
            if not has_body and "raise NotImplementedError" not in non_comment[i]:
                return False, "def_without_body"

    if not has_def:
        # if no def, check there is effective logic (not pure config)
        logic_lines = sum(1 for l in non_comment
                         if any(kw in l for kw in ['=', 'if ', 'for ', 'while ', 'return ', 'print(', 'yield ']))
        if logic_lines < 2:
            return False, "no_def_no_logic"

    # consecutive duplicate lines
    stripped = [l.strip() for l in non_comment]
    consec = 0
    for i in range(1, len(stripped)):
        if stripped[i] == stripped[i-1] and stripped[i]:
            consec += 1
            if consec >= 3:
                return False, "consecutive_repeated_lines"
        else:
            consec = 0

    # mean line length (anomaly signal)
    avg_len = sum(len(l) for l in non_comment) / max(effective, 1)
    if avg_len < 8:
        return False, f"avg_line_len={avg_len:.0f}"

    return True, "ok"


