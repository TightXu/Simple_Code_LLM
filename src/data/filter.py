def pre_tokenize_jsonl(input_path, output_bin, tokenizer, seq_len=1024):
    """JSONL -> .bin (mmap-compatible). Memory-friendly: uses array H instead of list."""
    import numpy as np
    from array import array
    from tqdm import tqdm

    texts = []
    with open(input_path, "r", encoding="utf-8") as f:
        for line in f:
            item = json.loads(line)
            if "text" in item:
                texts.append(item["text"] + "<eos>")
            elif "prompt" in item and "solution" in item:
                texts.append(item["prompt"] + item["solution"] + "<eos>")

    if not texts:
        print(f"  [FAIL] empty file: {input_path}")
        return

    n_texts = len(texts)
    print(f"  [WRITE] {n_texts:,} texts, tokenizing...")

    all_ids = array('H')
    batch_size = 256
    pbar = tqdm(total=n_texts, desc=f"  Tokenizing {Path(input_path).name}",
                unit="text", unit_scale=True)
    for i in range(0, n_texts, batch_size):
        batch = texts[i:i + batch_size]
        for enc in tokenizer.encode_batch(batch):
            ids_list = enc.ids
            max_id = max(ids_list) if ids_list else 0
            if max_id > 65535:
                raise ValueError(
                    f"Token ID {max_id} exceeds uint16 range (vocab={tokenizer.get_vocab_size()})."
                    f"  use uint32 or a smaller vocab."
                )
            all_ids.fromlist(ids_list)
        pbar.update(len(batch))
    pbar.close()

    total_tokens = (len(all_ids) // seq_len) * seq_len
    print(f"  [NUM] {len(all_ids):,} raw tokens -> truncate to {total_tokens:,} ({total_tokens/1e6:.1f}M)")

    ids_array = np.frombuffer(all_ids[:total_tokens], dtype=np.uint16).copy()
    ids_array.tofile(output_bin)

    # metadata
    meta = {
        "total_tokens": total_tokens,
        "vocab_size": tokenizer.get_vocab_size(),
        "seq_len": seq_len,
        "source": str(input_path),
        "dtype": "uint16",
        "created": datetime.now().isoformat(),
    }
    meta_path = str(output_bin).replace(".bin", "_meta.json")
    with open(meta_path, "w") as f:
        json.dump(meta, f, indent=2)

    file_size_mb = Path(output_bin).stat().st_size / 1e6
    print(f"  [OK] {total_tokens:,} tokens ({total_tokens/1e6:.1f}M), {file_size_mb:.1f} MB")

