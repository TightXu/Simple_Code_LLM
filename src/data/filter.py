def is_filename_poison(filepath: str) -> bool:
    """Filename / path-level filtering."""
    for pat in POISON_FILENAMES:
        if pat in filepath:
            return True
    for pat in POISON_PATH_PATTERNS:
        if fnmatch.fnmatch(filepath, pat):
            return True
    return False


