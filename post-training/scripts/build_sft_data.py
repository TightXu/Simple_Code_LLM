def iter_func_nodes(tree, allow_methods: bool):
    def walk(body):
        for node in body:
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                yield node
            elif allow_methods and isinstance(node, ast.ClassDef):
                yield from walk(node.body)
    yield from walk(tree.body)


def is_docstring_first(node) -> bool:
    b = node.body[0]
    return (isinstance(b, ast.Expr) and isinstance(b.value, ast.Constant)
            and isinstance(b.value.value, str))


def split_signature_body(src_lines, node, docstring_mode="strip"):
    """Return (prompt_text, solution_text); None when it is not a "single-line signature + body on the next line".

    The indentation subtlety: the prompt ends with "\\n    " (4 spaces) and those 4 spaces only indent the **first** line,
      so the solution body must be "dedented, then 4 spaces re-added to every line but the first",
      otherwise lines outside the def fall back to column 0 ('return' outside function).
    """
    first = node.body[0]
    # the def and the body's first statement must be on adjacent lines (excludes `def f(): return 1` and multi-line signatures)
    if first.lineno != node.lineno + 1:
        return None
    if node.lineno < 1 or node.lineno > len(src_lines):   # bounds check (leftover node from an exception / pre-normalization)
        return None
    sig = src_lines[node.lineno - 1]
    if not sig.rstrip().endswith(":"):
        cut = sig.split("#")[0].rstrip()          # trailing comment `def f(x):  # noqa`
        if cut.endswith(":"):
            sig = cut
        else:
            return None
    sig_core = sig.strip()
    if not re.match(r"^(async\s+def|def)\s", sig_core):
        return None

    start = first.lineno
    if is_docstring_first(node):
        if docstring_mode == "reject":
            return None
        if len(node.body) < 2:                    # the body is only a docstring → no solution
            return None
        start = node.body[1].lineno

    body_lines = src_lines[start - 1: node.end_lineno]
    ded = textwrap.dedent("\n".join(body_lines)).split("\n")
    out = [ded[0].rstrip()]
    out.extend(("    " + l.rstrip()) if l.strip() else "" for l in ded[1:])
    body = "\n".join(out).rstrip()
    if not body.strip():
        return None
    return sig_core + "\n    ", body


