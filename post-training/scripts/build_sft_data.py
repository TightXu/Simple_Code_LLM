def quality_reason(body: str) -> str | None:
    """L5 quality metrics (computed on the solution body)."""
    lines = body.split("\n")
    total = len(lines)
    if total < 2:
        return "L5_too_few_lines"
    non_comment = [l for l in lines if l.strip() and not l.strip().startswith("#")]
    effective = len(non_comment)
    if effective < 2:
        return f"L5_effective={effective}"

    import_count = sum(1 for l in non_comment if l.strip().startswith(("import ", "from ")))
    if import_count / effective > 0.6:
        return f"L5_import_ratio={import_count/effective:.0%}"

    class_count = sum(1 for l in non_comment
                      if l.strip().startswith(("class ", "@staticmethod", "@classmethod", "@property")))
    decorator_count = sum(1 for l in non_comment
                          if l.strip().startswith("@")
                          and not l.strip().startswith(("@staticmethod", "@classmethod", "@property")))
    if (class_count + decorator_count) / effective > 0.7:
        return f"L5_class_ratio={(class_count+decorator_count)/effective:.0%}"

    comment_ratio = sum(1 for l in lines if l.strip().startswith("#")) / total
    if comment_ratio > 0.8:
        return f"L5_comment_ratio={comment_ratio:.0%}"

    consec = 0
    stripped = [l.strip() for l in non_comment]
    for i in range(1, len(stripped)):
        if stripped[i] and stripped[i] == stripped[i - 1]:
            consec += 1
            if consec >= 3:
                return "L5_consecutive_repeat"
        else:
            consec = 0

    if sum(1 for l in non_comment if any(k in l for k in LOGIC_KWS)) < 1:
        return "L5_no_logic_line"
    return None


